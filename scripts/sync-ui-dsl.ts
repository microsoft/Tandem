import { createHash } from "node:crypto";
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const source = process.argv[2];
if (!source) throw new Error("Supply the Chat UI DSL checkout to vendor.");
const root = resolve(source);
const target = resolve(dirname(fileURLToPath(import.meta.url)), "..", "src", "vendor", "ui-dsl");
const metadata = JSON.parse(await readFile(join(root, "package.json"), "utf8"));
if (metadata.name !== "chat-ui-dsl") throw new Error("Expected the chat-ui-dsl module.");
const files = [
    "agent.js", "catalog.js", "context.js", "document.js", "index.js",
    "lucide-icons.js", "lucide-LICENSE", "renderer.css", "renderer.js", "stream.js",
];
await mkdir(target, { recursive: true });
const hashes: Record<string, string> = {};
for (const file of files) {
    const bytes = await readFile(join(root, "src", file));
    hashes[file] = createHash("sha256").update(bytes).digest("hex");
    await copyFile(join(root, "src", file), join(target, file));
}
const css = await readFile(join(target, "renderer.css"), "utf8");
await writeFile(join(target, "styles.ts"),
    "// Generated by scripts/sync-ui-dsl.ts from renderer.css. Do not edit.\n"
    + `export default ${JSON.stringify(css)};\n`);
await writeFile(join(target, "source.json"), JSON.stringify({
    name: metadata.name, version: metadata.version,
    description: "Unmodified library snapshot; excludes the standalone canvas, host and persistence.",
    files: hashes,
}, null, 2) + "\n");
